export type TranslationDictionary = typeof en;
export type Locale = 'en' | 'vi';
export type TranslationKey = string;

export function t(key: TranslationKey, params?: Record<string, string | number>): string {
  const value = key.split('.').reduce<unknown>((current, part) => {
    return current && typeof current === 'object' && part in current ? (current as Record<string, unknown>)[part] : undefined;
  }, en);
  if (typeof value !== 'string') return key;
  return value.replace(/\{(\w+)\}/g, (_, name: string) => String(params?.[name] ?? `{${name}}`));
}

export function translatedError(code: string, fallback: string): string {
  const translated = t(`errors.${code}`);
  return translated === `errors.${code}` ? fallback : translated;
}
